/**
 * Builds the SQL seed that loads one real venue record into Supabase.
 *
 * The seed loads facts only: it inserts the place as a draft (a re-run never
 * changes publication_state or published_at), replaces its child facts, and
 * leaves every follow-up fact stored but hidden by RLS.
 *
 * Publishing is a separate file (buildVenuePublishSql) that a person applies
 * on purpose after reviewing the loaded data. Nothing in the app runs either.
 */

import type { VenueRecord } from "@/data/discover/venueTypes";
import { VENUE_CHILD_TABLES, venueRecordToRows, type Row } from "@/lib/discover/venueRows";

export type SeedCity = {
  id: string;
  country: string;
  provinceState: string;
  cityTown: string;
  slug: string;
  tourismRegion: string | null;
};

const ENUM_CASTS: Record<string, string> = {
  category: "public.discover_category",
  setting: "public.place_setting",
  cost_tier: "public.place_cost_tier",
  hours_kind: "public.place_hours_kind",
  toddler_friendly: "public.confirmed_tri_state",
  stroller_friendly: "public.confirmed_tri_state",
  publication_state: "public.publication_state",
  operating_status: "public.place_operating_status",
};

export function sqlLiteral(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Non-finite number in seed: ${value}`);
    return String(value);
  }
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    return value.length ? `array[${value.map(sqlLiteral).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof value === "object") return `${sqlLiteral(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const uuidFor = (placeId: string, key: string) => `md5(${sqlLiteral(`${placeId}:${key}`)})::uuid`;

function insert(table: string, columns: string[], values: string[]): string {
  return `insert into public.${table} (${columns.join(", ")})\nvalues (${values.join(", ")});`;
}

export function buildVenueSeedSql(record: VenueRecord, city: SeedCity): string {
  const { place, children } = venueRecordToRows(record);
  const placeId = String(place.id);
  const out: string[] = [];

  out.push(
    `-- Seed: ${record.place.name}${record.place.branchName ? ` — ${record.place.branchName}` : ""} (${placeId})`,
    "-- Generated by scripts/discover/build-venue-seed.ts — edit the TypeScript record, not this file.",
    "--",
    "-- Loads the venue as a DRAFT. It does not publish: a new place is inserted",
    "-- with publication_state = 'draft', and a re-run never changes an existing",
    "-- place's publication_state or published_at. Facts marked needs_follow_up",
    "-- are stored but stay hidden by row-level security.",
    `-- To publish after review, apply ${placeId.toLowerCase()}-${record.place.slug}.publish.sql separately.`,
    "",
    "begin;",
    "",
    "-- City (kept if it already exists under this id or name).",
    `insert into public.cities (id, country, province_state, city_town, slug, tourism_region)\nvalues (${[
      city.id,
      city.country,
      city.provinceState,
      city.cityTown,
      city.slug,
      city.tourismRegion,
    ]
      .map(sqlLiteral)
      .join(", ")})\non conflict do nothing;`,
    city.tourismRegion
      ? `update public.cities set tourism_region = ${sqlLiteral(city.tourismRegion)}\nwhere id = ${sqlLiteral(city.id)} and tourism_region is null;`
      : "",
    "",
  );

  const cityExpr = `(select id from public.cities where id = ${sqlLiteral(city.id)}\n   union all\n   select id from public.cities where lower(city_town) = lower(${sqlLiteral(city.cityTown)}) and province_state = ${sqlLiteral(city.provinceState)}\n   limit 1)`;

  // publication_state comes from the record (always a draft); published_at is
  // never set here. On conflict both are left exactly as they are.
  if (place.publication_state !== "draft" || place.published_at !== null) {
    throw new Error(`${placeId}: seed records must be drafts with no published_at; publish separately.`);
  }
  const placeCols = Object.keys(place).filter((c) => c !== "published_at");
  const placeVals = placeCols.map((c) => {
    if (c === "city_id") return cityExpr;
    const lit = sqlLiteral(place[c]);
    return ENUM_CASTS[c] ? `${lit}::${ENUM_CASTS[c]}` : lit;
  });
  const updates = placeCols
    .filter((c) => c !== "id" && c !== "publication_state")
    .map((c) => `  ${c} = excluded.${c}`);
  out.push(
    "-- Place (draft; publication is untouched on re-run).",
    `insert into public.places (${placeCols.join(", ")})\nvalues (${placeVals.join(", ")})\non conflict (id) do update set\n${updates.join(",\n")};`,
    "",
    "-- Replace this place's facts.",
    ...[...VENUE_CHILD_TABLES]
      .reverse()
      .map((t) => `delete from public.${t} where place_id = ${sqlLiteral(placeId)};`),
    "",
  );

  for (const table of VENUE_CHILD_TABLES) {
    const rows = children[table];
    if (rows.length === 0) continue;
    out.push(`-- ${table}`);
    for (const row of rows as Row[]) {
      const cols = Object.keys(row).filter((c) => c !== "key" && c !== "review_source_key");
      const columns = ["id", "place_id", ...cols];
      const values = [uuidFor(placeId, String(row.key)), sqlLiteral(placeId), ...cols.map((c) => sqlLiteral(row[c]))];
      if (table === "place_experience_themes") {
        columns.push("review_source_id");
        values.push(row.review_source_key ? uuidFor(placeId, String(row.review_source_key)) : "null");
      }
      out.push(insert(table, columns, values));
    }
    out.push("");
  }

  out.push("commit;", "");
  return out.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}

/**
 * The explicit publish step for one place. Refuses (raises, rolls back) unless
 * the place exists, is open, and has its own source and check date — the same
 * conditions the page requires. Keeps an earlier published_at.
 */
export function buildVenuePublishSql(record: VenueRecord): string {
  const id = sqlLiteral(record.place.id);
  const name = `${record.place.name}${record.place.branchName ? ` — ${record.place.branchName}` : ""}`;
  return [
    `-- PUBLISH: ${name} (${record.place.id})`,
    "-- Generated by scripts/discover/build-venue-seed.ts.",
    "--",
    "-- Applying this file makes the venue page public (and indexable in production).",
    "-- Apply only after the draft seed is loaded and reviewed.",
    "",
    "begin;",
    "",
    "do $$",
    "declare n integer;",
    "begin",
    "  update public.places",
    "     set publication_state = 'published',",
    "         published_at = coalesce(published_at, timezone('utc', now()))",
    `   where id = ${id}`,
    "     and operating_status = 'open'",
    "     and source_url ~* '^https://'",
    "     and source_checked_date is not null;",
    "  get diagnostics n = row_count;",
    "  if n <> 1 then",
    `    raise exception 'Not published: ${record.place.id} is missing, not open, or has no source and check date';`,
    "  end if;",
    "end $$;",
    "",
    "commit;",
    "",
  ].join("\n");
}
